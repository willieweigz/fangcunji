def main():
    for s in stamps:
        md_content = gen_md(s)
        folder_path = os.path.join(BASE, s["folder"])
        md_filename = s["folder"] + ".md"
        md_path = os.path.join(folder_path, md_filename)

        if not os.path.isdir(folder_path):
            print("WARNING: 文件夹不存在 - {}".format(folder_path))
            continue

        with open(md_path, "w", encoding="utf-8") as f:
            f.write(md_content)
        print("OK: {}".format(md_filename))

    print("\n完成！共生成 {} 个md文件。".format(len(stamps)))


if __name__ == "__main__":
    main()
