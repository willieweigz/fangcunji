def gen_md(s):
    """根据数据字典生成md内容"""
    lines = []
    # 标题
    lines.append("# {} \u300a{}\u300b".format(s["id"], s["title"]))
    lines.append("")

    # 发行公告头
    stamp_count = len(s["stamps_list"])
    header = "中国邮政定于{}发行\u300a{}\u300b{}1套{}枚".format(
        s["date"], s["title"], s["type"], stamp_count
    )
    if s.get("header_extra"):
        header += s["header_extra"]
    header += "。详情如下："
    lines.append(header)
    lines.append("")

    # 枚列表
    for fmt, name, denom in s["stamps_list"]:
        lines.append("{} {} {}".format(fmt, name, denom))
        lines.append("")

    # 规格信息
    for spec in s.get("specs", []):
        lines.append(spec)
    lines.append("")

    # 版别
    if s.get("version"):
        lines.append("版别：{}".format(s["version"]))
        lines.append("")

    # 防伪方式（如果specs里没有单独列出）
    if not any("防伪方式" in spec for spec in s.get("specs", [])):
        lines.append("防伪方式：防伪纸张、防伪油墨、异形齿孔、荧光喷码")
        lines.append("")

    # 设计者
    if s.get("designer"):
        lines.append("设计者：{}".format(s["designer"]))
    if s.get("extra_design"):
        lines.append(s["extra_design"])
    if s.get("data_provider"):
        lines.append("资料提供：{}".format(s["data_provider"]))
    lines.append("")

    # 印制厂
    if s.get("printer"):
        lines.append("印制厂：{}".format(s["printer"]))
        lines.append("")

    # 计划发行数量
    if s.get("quantity"):
        lines.append("计划发行数量：{}".format(s["quantity"]))
        lines.append("")

    # 出售办法
    lines.append(SELL_TEXT)
    lines.append("")

    # 注（特殊版式）
    if s.get("note"):
        lines.append("注：{}".format(s["note"]))
        lines.append("")

    # 背景概述段
    lines.append(s["overview"])
    lines.append("")

    # 背景资料段
    lines.append(s["background"])
    lines.append("")

    # 制作信息行
    maker_parts = []
    if s.get("designer"):
        maker_parts.append("由{}设计".format(s["designer"]))
    if s.get("editor"):
        maker_parts.append("{}编辑".format(s["editor"]))
    if s.get("printer"):
        maker_parts.append("{}{}工艺印制".format(s["printer"], s.get("version", "")))
    if maker_parts:
        lines.append("该套邮票{}".format("，".join(maker_parts) + "。"))
        lines.append("")

    # 结尾段
    lines.append(ENDING)

    return "\n".join(lines) + "\n"


