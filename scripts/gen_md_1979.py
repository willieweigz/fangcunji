def gen_md(s):
    lines = []
    lines.append(f"# {s['id']} 《{s['title']}》")
    lines.append("")
    lines.append(f"**发行日期**：{s['date']}")
    lines.append("")
    lines.append("**枚数·面值·图名·发行量**：")
    lines.append("")
    for i, (sn, name, val, qty) in enumerate(s["stamps"], 1):
        lines.append(f"{i}. {val} {name} {qty}")
    lines.append("")
    lines.append(f"**邮票规格**：{s['size']}")
    lines.append(f"**齿孔度数**：{s['perf']}")
    lines.append(f"**整张枚数**：{s['sheet']}")
    lines.append(f"**版别**：{s['version']}")
    lines.append(f"**设计者**：{s['designer']}")
    lines.append(f"**印制厂**：{s['printer']}")
    lines.append("")
    lines.append("## 背景介绍")
    lines.append("")
    lines.append(s["bg"])
    if s["note"]:
        lines.append("")
        lines.append(s["note"])
    lines.append("")
    return "\n".join(lines)


def main():
    for s in STAMPS:
        folder = os.path.join(BASE, s["folder"])
        if not os.path.isdir(folder):
            print(f"❌ 文件夹不存在: {s['folder']}")
            continue
        md_name = f"{s['folder']}.md"
        md_path = os.path.join(folder, md_name)
        content = gen_md(s)
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"✅ {s['id']} {s['title']}")
    print(f"\n共生成 {len(STAMPS)} 个MD文件")


if __name__ == "__main__":
    main()
