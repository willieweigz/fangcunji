result = []
for sid, title, typ, date, themes, total, extras, desc, stamps_data, extra_stamps in SETS:
    stamps = []
    for sn, name, den, has_ind in stamps_data:
        img = f"/images/stamps/2017/{sid}-{sn}.jpg" if has_ind else ""
        stamps.append({"sn": sn, "name": name, "denomination": den, "image": img})
    for sn, name, den, fmt in extra_stamps:
        img = f"/images/stamps/2017/{sid}-{sn}.jpg"
        stamps.append({"sn": sn, "name": name, "denomination": den, "image": img, "format": fmt})
    result.append({
        "id": sid, "title": title, "type": typ, "issueDate": date,
        "year": 2017, "series": "编年", "themes": themes, "designer": "",
        "totalStamps": total, "extras": extras, "description": desc, "stamps": stamps,
    })

out = "data/stamps/2017.json"
with open(out, "w", encoding="utf-8") as f:
    json.dump(result, f, ensure_ascii=False, indent=2)
    f.write("\n")

total_stamps = sum(len(s["stamps"]) for s in result)
total_regular = sum(s["totalStamps"] for s in result)
print(f"Generated {out}: {len(result)} sets, {total_regular} regular + {total_stamps - total_regular} extra = {total_stamps} records")
