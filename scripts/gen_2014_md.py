def generate_md(s):
    lines = []
    # 标题
    lines.append(f"# {s['title']}")
    lines.append("")
    # 发行公告头
    header = f"中国邮政定于{s['date']}发行《{s['title']}》{s['type']}1套{len(s['stamps_list'])}枚"
    if s.get("header_extra"):
        header += s["header_extra"]
    header += "。详情如下："
    lines.append(header)
    lines.append("")
    # 枚列表
    for fmt, name, denom in s["stamps_list"]:
        lines.append(f"{fmt} {name} {denom}")
        lines.append("")
    # 规格信息
    for spec in s["specs"]:
        lines.append(spec)
    lines.append("")
    # 版别
    lines.append(f"版别：{s['version']}")
    lines.append("")
    # 设计者
    lines.append(f"设计者：{s['designer']}")
    if s.get("extra_design"):
        lines.append(s["extra_design"])
    if s.get("data_provider"):
        lines.append(f"资料提供：{s['data_provider']}")
    lines.append("")
    # 印制厂
    lines.append(f"印制厂：{s['printer']}")
    lines.append("")
    # 计划发行数量
    lines.append(f"计划发行数量：{s['quantity']}")
    lines.append("")
    # 出售办法
    lines.append(SELL_TEXT)
    lines.append("")
    # 注
    if s.get("note"):
        lines.append(f"注：{s['note']}")
        lines.append("")
    # 背景概述段
    lines.append(s["overview"])
    lines.append("")
    # 背景资料段
    lines.append(s["background"])
    lines.append("")
    # 制作信息行
    maker_line = f"该套邮票由{s['designer']}设计"
    if s.get("data_provider"):
        maker_line += f"，{s['data_provider']}提供资料"
    maker_line += f"，{s['printer']}印制。"
    lines.append(maker_line)
    lines.append("")
    # 结尾段
    lines.append(ENDING)
    lines.append("")
    return "\n".join(lines)


def main():
    for s in stamps:
        folder_path = os.path.join(BASE, s["folder"])
        md_filename = s["folder"] + ".md"
        md_path = os.path.join(folder_path, md_filename)
        content = generate_md(s)
        os.makedirs(folder_path, exist_ok=True)
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"OK: {md_filename}")
    print(f"\n总计: {len(stamps)} 套")


if __name__ == "__main__":
    main()
