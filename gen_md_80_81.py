def gen_md(title, d):
    lines = [f'# {title}', '']
    lines.append(f'**发行日期**：{d["date"]}')
    lines.append('')
    lines.append('**枚数·面值·图名·发行量**：')
    lines.append('')
    for i, (denom, name, qty) in enumerate(d['stamps'], 1):
        lines.append(f'{i}. {denom} {name} {qty}')
    lines.append('')
    lines.append(f'**邮票规格**：{d["spec"]}')
    lines.append(f'**齿孔度数**：{d["perf"]}')
    lines.append(f'**整张枚数**：{d["sheet"]}')
    lines.append(f'**版别**：{d["print"]}')
    lines.append(f'**设计者**：{d["designer"]}')
    if 'engraver' in d:
        lines.append(f'**雕刻者**：{d["engraver"]}')
    if 'original_artist' in d:
        lines.append(f'**原画作者**：{d["original_artist"]}')
    lines.append(f'**印制厂**：{d["factory"]}')
    if 'extras' in d:
        lines.append(f'**附注**：含{d["extras"]}')
    if 'mini' in d:
        m = d['mini']
        mini_id = title.split(' ')[0] + 'M'
        lines.append('')
        lines.append(f'## {mini_id} {title}（小型张）')
        lines.append('')
        lines.append(f'**面值**：{m["denom"]}')
        lines.append(f'**图名**：{m["name"]}')
        lines.append(f'**发行量**：{m["issue"]}')
        lines.append(f'**规格**：{m["spec"]}')
        lines.append(f'**版别**：{m["print"]}')
    lines.append('')
    lines.append('## 背景介绍')
    lines.append('')
    lines.append(d['intro'])
    return '\n'.join(lines)


