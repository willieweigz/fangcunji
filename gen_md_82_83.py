# -*- coding: utf-8 -*-
import os

BASE = r"G:\微云同步文件夹\邮票网站\新中国邮票图片全集（1949年-2026年最新）"

def write_md(folder_year, stamp_key, info):
    year_dir = os.path.join(BASE, folder_year)
    target_dir = os.path.join(year_dir, stamp_key)
    if not os.path.isdir(target_dir):
        print(f"  SKIP (folder not found): {stamp_key}")
        return
    md_path = os.path.join(target_dir, stamp_key + ".md")
    
    lines = []
    lines.append(f"# {info['title']}")
    lines.append("")
    lines.append(f"**发行日期**：{info['date']}")
    lines.append("")
    
    lines.append("**枚数·面值·图名·发行量**：")
    lines.append("")
    for i, (den, name, qty) in enumerate(info['stamps'], 1):
        lines.append(f"{i}. {den} {name} {qty}")
    lines.append("")
    
    lines.append(f"**邮票规格**：{info['spec']}")
    lines.append(f"**齿孔度数**：{info['perf']}")
    lines.append(f"**整张枚数**：{info['sheet']}")
    lines.append(f"**版别**：{info['print']}")
    lines.append(f"**设计者**：{info['designer']}")
    if info.get('engraver'):
        lines.append(f"**雕刻者**：{info['engraver']}")
    if info.get('original_painter'):
        lines.append(f"**原画作者**：{info['original_painter']}")
    if info.get('photographer'):
        lines.append(f"**摄影者**：{info['photographer']}")
    lines.append(f"**印制厂**：{info['factory']}")
    
    if info.get('extras'):
        lines.append(f"**附注**：含{info['extras']}")
    
    if info.get('miniature_sheet'):
        ms = info['miniature_sheet']
        lines.append("")
        lines.append(f"## {ms['name']}")
        lines.append("")
        lines.append(f"**面值**：{ms['denomination']}")
        lines.append(f"**图名**：{ms['name_detail']}")
        lines.append(f"**发行量**：{ms['quantity']}")
        lines.append(f"**规格**：{ms['spec']}")
        lines.append(f"**版别**：{ms['print']}")
        if ms.get('engraver'):
            lines.append(f"**雕刻者**：{ms['engraver']}")
    
    lines.append("")
    lines.append("## 背景介绍")
    lines.append("")
    lines.append(info['intro'].strip())
    lines.append("")
    
    content = "\n".join(lines)
    with open(md_path, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f"  OK: {stamp_key}")

